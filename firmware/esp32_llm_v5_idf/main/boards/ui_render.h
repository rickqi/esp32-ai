// ---- UTF-8 decode (returns codepoint, sets *consumed) ---------------------
static inline int ui_utf8_decode(const unsigned char *s, int len, int *consumed) {
  unsigned char b0 = s[0];
  if (b0 < 0x80) { *consumed = 1; return b0; }
  if ((b0 & 0xE0) == 0xC0 && len >= 2) {
    *consumed = 2;
    return ((b0 & 0x1F) << 6) | (s[1] & 0x3F);
  }
  if ((b0 & 0xF0) == 0xE0 && len >= 3) {
    *consumed = 3;
    return ((b0 & 0x0F) << 12) | ((s[1] & 0x3F) << 6) | (s[2] & 0x3F);
  }
  *consumed = 1;
  return -1;
}

// ---- binary search CJK_CP -> glyph index ----------------------------------
static inline int ui_cjk_find(int cp) {
  int lo = 0, hi = CJK_N - 1;
  while (lo <= hi) {
    int mid = (lo + hi) >> 1;
    if (CJK_CP[mid] < cp) lo = mid + 1;
    else if (CJK_CP[mid] > cp) hi = mid - 1;
    else return mid;
  }
  return -1;
}

// ---- draw one 5x7 ASCII glyph at (x,y) ------------------------------------
static inline void ui_draw_char(DisplayPort *d, int x, int y, unsigned char c) {
  if (c >= 128) return;
  const uint8_t *g = &UI_FONT_5X7[(unsigned)c * 5];
  for (int col = 0; col < 5; col++) {
    uint8_t bits = g[col];
    for (int row = 0; row < 8; row++)
      if (bits & (1 << row)) d->RLCD_SetPixel(x + col, y + row, ColorBlack);
  }
}

// ---- draw one 14x14 CJK glyph at (x,y), missing -> hollow box -------------
static inline void ui_draw_cjk(DisplayPort *d, int x, int y, int cp) {
  int idx = ui_cjk_find(cp);
  if (idx < 0) {   // missing glyph: 2px border box
    for (int i = 0; i < UI_CJK_W; i++) {
      d->RLCD_SetPixel(x + i, y, ColorBlack);
      d->RLCD_SetPixel(x + i, y + UI_CJK_H - 1, ColorBlack);
    }
    for (int j = 0; j < UI_CJK_H; j++) {
      d->RLCD_SetPixel(x, y + j, ColorBlack);
      d->RLCD_SetPixel(x + UI_CJK_W - 1, y + j, ColorBlack);
    }
    return;
  }
  const uint8_t *g = &CJK_BLOB[CJK_OFF[idx]];
  for (int row = 0; row < UI_CJK_H; row++) {
    for (int col = 0; col < UI_CJK_W; col++) {
      if (g[row * 2 + col / 8] & (0x80 >> (col % 8)))
        d->RLCD_SetPixel(x + col, y + row, ColorBlack);
    }
  }
}

// ---- draw UTF-8 string at (x,y), no wrap ----------------------------------
static inline int ui_text(DisplayPort *d, int x, int y, const char *s) {
  int cx = x;
  const unsigned char *p = (const unsigned char *)s;
  while (*p) {
    int consumed;
    int cp = ui_utf8_decode(p, 8, &consumed);
    if (cp < 0) { p++; continue; }
    if (cp == '\n') { y += UI_ROW_H; cx = x; }
    else if (cp >= 32 && cp < 0x80) {
      ui_draw_char(d, cx, y + (UI_ROW_H - UI_CH) / 2, (unsigned char)cp);
      cx += UI_CW;
    } else if (cp >= 0x80) {
      ui_draw_cjk(d, cx, y, cp);
      cx += UI_CJK_W;
    }
    p += consumed;
  }
  return cx - x;   // consumed width
}

// ---- clear rectangle to white ---------------------------------------------
static inline void ui_clear_rect(DisplayPort *d, int x0, int y0, int x1, int y1) {
  for (int y = y0; y <= y1; y++)
    for (int x = x0; x <= x1; x++)
      d->RLCD_SetPixel(x, y, ColorWhite);
}

// ---- fill rectangle black --------------------------------------------------
static inline void ui_fill_rect(DisplayPort *d, int x0, int y0, int x1, int y1) {
  for (int y = y0; y <= y1; y++)
    for (int x = x0; x <= x1; x++)
      d->RLCD_SetPixel(x, y, ColorBlack);
}

